# Write src/scenes/index.ts from episode.json ("scenes" + "banners") and a stub file for every scene that doesn't exist yet.
#   usage (from a project dir): python3 $PAPERCUT_LIB/papercut/stubs.py
import json
import os

EP = json.load(open("episode.json"))
scene_list = EP.get("scenes", [])
ids = []
scene_dict = {}

# Check for storyboard.json to discover planned multi-environment layout per scene
storyboard_candidates = [
    "../storyboard/storyboard.json",
    "storyboard/storyboard.json",
    "../content_factory/storyboard.json",
    "content_factory/storyboard.json"
]
storyboard_data = None
for sb_cand in storyboard_candidates:
    if os.path.exists(sb_cand):
        try:
            with open(sb_cand, "r", encoding="utf-8") as f:
                storyboard_data = json.load(f)
                break
        except Exception:
            pass

if storyboard_data and isinstance(storyboard_data.get("scenes"), list):
    for sb_s in storyboard_data["scenes"]:
        if isinstance(sb_s, dict) and sb_s.get("id"):
            scene_dict[sb_s["id"]] = sb_s

for s in scene_list:
    if isinstance(s, str):
        sid = s
    elif isinstance(s, (list, tuple)):
        sid = s[0]
    elif isinstance(s, dict):
        sid = s.get("id")
        if sid and sid not in scene_dict:
            scene_dict[sid] = s
        elif sid and isinstance(scene_dict.get(sid), dict):
            scene_dict[sid].update(s)
    else:
        continue
    ids.append(sid)

B = EP.get("banners", {})
imp = "\n".join(f"import {{{i}}} from './{i}';" for i in ids)

def _clean_banner(val: str) -> str:
    import re
    return re.sub(r"^SKENARIO\s+WHAT-IF(?:\s*\([^)]*\))?\s*:\s*", "", val, flags=re.IGNORECASE).strip()

# Dynamic Banner Rule: Only Scene 1 (Hook) receives a headline banner.
# Scenes 2+ omit banner for vertical breathing room and demonstration clearance.
rows = "\n".join(
    f"  {{id: '{i}', component: {i}, banner: {json.dumps(_clean_banner(B.get(i, '')) if idx == 0 else '', ensure_ascii=False)}, band: 0.77}},"
    for idx, i in enumerate(ids)
)

open("src/scenes/index.ts", "w").write(f"""// Scene registry (generated by papercut/stubs.py from episode.json): id → component, banner (fact track), caption band.
import React from 'react';
{imp}

export type SceneDef = {{id: string; component: React.FC; banner: string; band: number}};
export const SCENES: SceneDef[] = [
{rows}
];
""")

default_env = EP.get("environment", {}).get("id", "science-lab") if isinstance(EP.get("environment"), dict) else (EP.get("environment") or "science-lab")

made = 0
for i in ids:
    p = f"src/scenes/{i}.tsx"
    if os.path.exists(p):
        continue

    sc = scene_dict.get(i, {})
    scene_env = sc.get("environment_id") or sc.get("environment") or default_env

    open(p, "w").write(f"""import React from 'react';
import {{PapercraftSceneShell}} from '../lib/scenes';
import {{durOf, scene}} from '../scene';

const ID = '{i}';

/**
 * {i}: 2D Papercraft Explainer Scene Component.
 * Supports dynamic presenter kinematics, audio-driven lip-sync, and text safe zones.
 */
export const {i}: React.FC = () => {{
  const dur = durOf(ID);
  const s = scene(ID);

  return (
    <PapercraftSceneShell
      id={{ID}}
      durationInFrames={{dur}}
      environment="{scene_env}"
      sceneType="demonstration_scene"
      presenter={{{{
        x: 360,
        y: 1380,
        size: 240,
        state: 'explaining',
        face: 1,
        glasses: true,
        labCoat: true,
      }}}}
      dialogue={{{{
        words: s.words,
        mode: 'audio_driven',
      }}}}
    />
  );
}};
""")
    made += 1

print(len(ids), "scenes in index.ts,", made, "new stubs generated using approved PapercraftSceneShell & CatScientist")
